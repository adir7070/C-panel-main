/* The per-run client snapshot — changes every run → NOT cached. */
function buildContextPrompt(view) {
  const L = [];
  L.push(`# הלקוח שמולך עכשיו`);
  if (view.clientName) L.push(`שם: ${view.clientName}`);
  if (view.tier) L.push(`רמת לקוח: ${view.tier}`);
  L.push("");

  if (view.clientMemory?.length) {
    L.push(`## זיכרון הלקוח — עובדות שנלמדו עליו לאורך זמן`);
    view.clientMemory.forEach(f => L.push(`- ${f}`));
    L.push(`השתמש בעובדות האלה בטבעיות (התאם הצעות, טון והחלטות) — אל תצטט אותן ללקוח ואל תספר לו ש"רשום עליו" משהו. אם הלקוח אומר משהו שסותר עובדה — העדף את דבריו העדכניים ושמור את העדכון עם remember_client_fact.`);
    L.push("");
  }

  if (view.profile) {
    const p = view.profile;
    L.push(`## פרופיל העסק`);
    if (p.businessName) L.push(`עסק: ${p.businessName}`);
    if (p.businessField) L.push(`תחום: ${p.businessField}`);
    if (p.about) L.push(`תיאור: ${p.about}`);
    if (p.services?.length) L.push(`שירותים: ${p.services.join("; ")}`);
    if (p.serviceRefs?.length) L.push(`מזהי שירותים (לשיוך תמונות עם attach_image_to_service): ${p.serviceRefs.map(s => `"${s.title}"=${s.id}`).join(" · ")}`);
    if (p.targetAudience?.length) L.push(`קהל יעד: ${p.targetAudience.join(", ")}`);
    if (p.preferredColors) L.push(`צבעי מותג: ${JSON.stringify(p.preferredColors)}`);
    L.push("");
  } else {
    L.push(`## פרופיל העסק: לא קיים פרופיל מלא במערכת.`);
    L.push("");
  }

  // Coins are HIDDEN from the client — never rendered here, and the agent must
  // not discuss tokens/costs. All actions are "included in the subscription".
  if (view.account?.package) {
    L.push(`## חשבון`);
    L.push(`חבילה: ${view.account.package.name || "—"} (סטטוס: ${view.account.package.status || "—"})`);
    L.push("");
  }

  const perf = view.performance;
  L.push(`## ביצועי פרסום (חי מפייסבוק)`);
  if (perf.skipped) {
    // light-depth run: live FB was not fetched — don't render a misleading "0 campaigns"
    L.push(`נתוני הקמפיינים לא נטענו בתור הזה (הודעה קצרה). אם התשובה דורשת נתונים — קרא ל-get_performance.`);
  } else {
  if (perf.campaignsError) L.push(`⚠️ שים לב: ${perf.campaignsError}`);
  L.push(`קמפיינים: ${perf.totalCampaigns} סה"כ, ${perf.activeCampaigns} פעילים. הוצאה ב-14 ימים: ${perf.spend14d}₪. לידים ב-14 ימים: ${perf.leads14d.total}.`);
  if (perf.campaigns?.length) {
    L.push(`טבלת קמפיינים:`);
    perf.campaigns.forEach(c => {
      L.push(`- [${c.id}] "${c.name}" | ${c.status} | תקציב יומי ${c.dailyBudget ?? "—"}₪ | הוצאה היום ${c.spendToday ?? 0}₪ | לידים היום ${c.leadsToday ?? 0} | CTR ${c.ctr ?? "—"}% | מטרה ${c.objective ?? "—"}`);
    });
  }
  if (perf.leads14d.byDay?.length) {
    const tail = perf.leads14d.byDay.slice(-7);
    L.push(`לידים/הוצאה לפי יום (7 אחרונים): ${tail.map(d => `${d.date}: ${d.leads} לידים / ${Math.round(d.spend)}₪`).join(" | ")}`);
  }
  if (view.benchmark) {
    const b = view.benchmark;
    const parts = [];
    if (b.categoryCPL) parts.push(`בתחום של הלקוח: ${b.categoryCPL}₪ לליד (${b.categoryClients} לקוחות)`);
    if (b.overallCPL) parts.push(`בכלל לקוחות Kliq: ${b.overallCPL}₪ לליד (${b.overallClients} לקוחות)`);
    L.push(`בנצ'מרק פנימי של Kliq (30 ימים): ${parts.join(" · ")}. השתמש בזה לכיול השיפוט — "טוב/יקר ביחס לממוצע אצלנו" במקום התרשמות כללית. אלה נתונים פנימיים: אל תחשוף שמות/נתונים של לקוחות אחרים, מותר לצטט את הממוצע עצמו.`);
  }
  }
  L.push("");

  if (view.recentAgentActions?.length) {
    L.push(`## פעולות אחרונות שלך (היסטוריה)`);
    view.recentAgentActions.forEach(a => {
      L.push(`- ${a.tool || "—"} | ${a.status} ${a.summary ? `| ${a.summary}` : ""}`);
    });
    L.push("");
  }

  L.push(`כל המספרים למעלה אמיתיים. אל תמציא מספרים אחרים. אם חסר מידע — קרא לכלי קריאה או אמור שאינך יודע.`);
  return L.join("\n");
}

