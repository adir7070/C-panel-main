  lines.push(`1. **השג תמונה חדשה** — אם הלקוח רוצה AI, קרא ל-generate_ad_image; אם הוא העלה תמונה משלו, קרא ל-edit_ad_image. שניהם מחזירים imageUrl ומציגים את התמונה ללקוח.`);
  lines.push(`2. **הצג ללקוח וקבל אישור קצר** שזו התמונה שהוא רוצה, ואז קרא ל-**update_ad_image** עם ה-adId (מ-get_campaign_ads) וה-imageUrl שהוחזר. זהו — התמונה מוחלפת במודעה החיה.`);
  lines.push(`- זו פעולה בטוחה (לא מוציאה תקציב) שמתבצעת אוטומטית וכלולה במנוי. פועל על מודעות תמונה בלבד — במודעת וידאו הכלי יחזיר שגיאה, ואז אפשר לשנות טקסט/לינק/כפתור בלבד.`);
  lines.push(`- אל תבלבל בין "תמונה חדשה" סתם (generate_ad_image — רק יוצר ומציג) לבין "החלף את התמונה **במודעה**" (generate/edit ואז **update_ad_image** שמחליף בפועל).`);
