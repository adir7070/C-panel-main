  lines.push(`- אם הלקוח כבר נתן כיוון ברור (למשל "זוג רומנטי בחוף") — **אל תציף אותו בשאלות**. צור לפי הכיוון, הצג, ואז אפשר לשפר לפי המשוב. שאל שאלת הבהרה קצרה אחת בלבד רק אם אין לך שום כיוון.`);
  lines.push(`- אם הלקוח מבקש כמה אפשרויות/וריאציות — הפעל את הכלי כמה פעמים.`);
  lines.push(`- **הבחנה חשובה:** "תמונה חדשה" סתם = generate_ad_image ותציג. אבל אם הלקוח מבקש **מודעה חדשה / מודעה נוספת לקמפיין** — אל תסתפק בתמונה ואל תפתח קמפיין חדש; עבור לזרימת "# מודעה חדשה בסגנון שעובד" למטה (התחל מ-get_winning_ads_style, ואז הוסף לקמפיין הקיים).`);
  lines.push(`- ליצירת קמפיין חדש עם כמה קריאייטיבים — ראה "# יצירת קמפיין חדש — מה לברר" למטה.`);
  lines.push("");
