const chatWithBrief = async (history, userMessage) => {
  const messages = [
    { role: 'system', content: SYSTEM_PROMPT },
    ...history,
    { role: 'user', content: userMessage },
  ];

  let lastErr;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const response = await openai.chat.completions.create({
        model: MODEL,
        messages,
        max_completion_tokens: 500,
      });

      const assistantMessage = response.choices[0]?.message?.content || '';

      let briefData = { isComplete: false };
      const jsonMatch = assistantMessage.match(/<!--BRIEF_DATA:(.*?)-->/);
      if (jsonMatch) {
        try { briefData = JSON.parse(jsonMatch[1]); } catch { /* */ }
      }

      const cleanReply = assistantMessage.replace(/<!--BRIEF_DATA:.*?-->/s, '').trim();

      const newHistory = [
        ...history,
        { role: 'user', content: userMessage },
        { role: 'assistant', content: assistantMessage },
      ];

      return { reply: cleanReply, briefData, history: newHistory };
    } catch (err) {
      lastErr = err;
      if (err?.status === 429 && attempt < 2) {
        const wait = (attempt + 1) * 10000;
        console.log(`Rate limited, waiting ${wait/1000}s...`);
        await new Promise(r => setTimeout(r, wait));
      } else {
        break;
      }
    }
  }

  throw lastErr;
};

const startChat = async () => {
  try {
    const messages = [
      { role: 'system', content: SYSTEM_PROMPT },
      { role: 'user', content: 'היי' },
    ];

    const response = await openai.chat.completions.create({
      model: MODEL,
      messages,
      max_completion_tokens: 300,
    });

    const assistantMessage = response.choices[0]?.message?.content || '';
    const cleanReply = assistantMessage.replace(/<!--BRIEF_DATA:.*?-->/s, '').trim();

    const history = [
      { role: 'user', content: 'היי' },
      { role: 'assistant', content: assistantMessage },
    ];

    return { reply: cleanReply, history };
  } catch (err) {
    const fallbackReply = 'שלום! אני כאן כדי לעזור לך ליצור דף נחיתה מושלם. נתחיל — מה שם העסק שלך?';
    const fallbackHistory = [
      { role: 'user', content: 'היי' },
      { role: 'assistant', content: fallbackReply },
    ];
    if (err?.status === 429) {
      return { reply: fallbackReply, history: fallbackHistory };
    }
    throw err;
  }
};

