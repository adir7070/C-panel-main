/**
 * WOW LP v2 — Template-driven landing-page renderer.
 *
 * Replaces the deterministic single-template engine (utils/wow-lp-template.js)
 * with a system that ships the agency's hand-crafted templates verbatim and
 * fills in business-specific content via `{{KEY}}` placeholders.
 *
 * Each template lives at services/wow-lp-templates/<name>/ with:
 *   index.html  — the structural HTML, with {{BUSINESS_NAME}} / {{PHONE}}
 *                 / {{HERO_TITLE}} / ... placeholders wherever business-
 *                 specific content needs to flow in.
 *   styles.css  — visual design (inlined into the rendered output).
 *   script.js   — interactions (inlined too — output is a single file).
 *   keys.json   — { keyName: "description for the AI" } so we can prompt
 *                 the model with the right context per key.
 *
 * Pipeline:
 *   1. pickTemplate(brief)         — choose a template by industry
 *   2. loadTemplate(name)          — read HTML/CSS/JS/keys from disk
 *   3. generateInjectValues(brief, keys)
 *                                   — single gpt-4o call returns
 *                                     { "BUSINESS_NAME": "...", ... }
 *   4. substitutePlaceholders(html, values)
 *                                   — literal string-replace every
 *                                     {{KEY}} occurrence
 *   5. inlineAssets(html, css, js) — embed CSS into <style>, JS before
 *                                    </body>; rewrite image paths so the
 *                                    deployed HTML can find them.
 *
 * Returns a single self-contained HTML string ready to ship to Netlify or
 * serve as the LP preview.
 */

