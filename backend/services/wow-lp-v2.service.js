function loadTemplate(name) {
  const root = path.join(TEMPLATES_DIR, name);
  if (!fs.existsSync(path.join(root, "index.html"))) {
    throw new Error(`Template "${name}" not found at ${root}`);
  }
  const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
  /* Try a few common css/js file names — different demos shipped with
     slightly different conventions (styles.css vs css/style.css). */
  const css = readFirstExisting([
    path.join(root, "styles.css"),
    path.join(root, "css", "style.css"),
    path.join(root, "css", "styles.css"),
  ]);
  const js = readFirstExisting([
    path.join(root, "script.js"),
    path.join(root, "js", "main.js"),
    path.join(root, "js", "script.js"),
  ]);
  let keys = {};
  const keysPath = path.join(root, "keys.json");
  if (fs.existsSync(keysPath)) {
    try { keys = JSON.parse(fs.readFileSync(keysPath, "utf8")); }
    catch (e) { console.warn(`[wow-lp-v2] ${name}/keys.json parse error:`, e.message); }
  }
  return { name, html, css, js, keys };
}

function readFirstExisting(paths) {
  for (const p of paths) {
    if (fs.existsSync(p)) return fs.readFileSync(p, "utf8");
  }
  return "";
}

/**
 * Walk the HTML looking for {{KEY}} placeholders and return the unique
 * set, sorted. Used to validate that every key documented in keys.json
 * actually appears in the template and vice-versa. */
function listPlaceholders(html) {
  const out = new Set();
  const re = /\{\{([A-Z][A-Z0-9_]*)\}\}/g;
  let m;
  while ((m = re.exec(html))) out.add(m[1]);
  return [...out].sort();
}

/* Quality bar: every LP we ship should have at least this many
   <section> blocks. Templates that come in below the floor get
   AI-extended at render time (see generateExtraSections). */
const MIN_SECTIONS = 15;

function countSections(html) {
  const m = html.match(/<section\b/gi);
  return m ? m.length : 0;
}

/* Strip industry-specific examples from a keys.json description so
   the AI doesn't drift into the example's industry when filling for
   a totally different business. Removes parenthetical examples
   ("(לדוגמה ...)"), "לדוגמה X" / "למשל X" clauses and their quoted
   strings, "כמו 'X'" comparisons, and trailing example fragments.
   The slot's purpose / length / structure cues stay intact. */
function stripExamplesFromDescription(desc) {
  if (!desc || typeof desc !== "string") return "";
  return desc
    /* Parenthetical examples with leading marker. */
    .replace(/\([^)]*?(?:לדוגמ[הא]|למשל|דוגמ[הא])[^)]*\)/gi, "")
    /* "לדוגמה / למשל / דוגמא" + the rest of the clause up to next sentence. */
    .replace(/[,;\s]*(?:לדוגמ[הא]|למשל|דוגמ[הא])[^.!?]*?(?=[.!?]|$)/gi, "")
    /* "כמו 'X'" / 'כמו "X"' style comparisons. */
    .replace(/[,;\s]*כמו\s*['"‘’“”][^'"‘’“”]+['"‘’“”]/gi, "")
    /* English: "e.g. ...", "i.e. ...", "such as ..." clauses. */
    .replace(/[,;\s]*(?:e\.g\.|i\.e\.|such\s+as)[^.!?]*?(?=[.!?]|$)/gi, "")
    /* Collapse double spaces and trim. */
    .replace(/\s{2,}/g, " ")
    .trim();
}

/* Pull the first 1-2 <section> blocks from the template as a style
   reference for the AI. Sent to gpt-4o together with the styles.css
   so the model can extend the page in the existing design language
   without inventing new classes, colors, or spacing tokens. */
function sampleSectionsForStyleReference(html, count = 2) {
  const samples = [];
  const re = /<section\b[^>]*>[\s\S]*?<\/section>/gi;
  let m;
  while ((m = re.exec(html)) && samples.length < count) {
    /* Truncate very long samples to keep the prompt cheap. */
    const sample = m[0].length > 2400 ? m[0].slice(0, 2400) + "\n<!-- ...truncated -->" : m[0];
    samples.push(sample);
  }
  return samples;
}

