/* ── Image generation (Gemini) ────────────────────────────────────── */

/* A placeholder is an "image key" when it stands in for a <img src=…>,
   a CSS background-image URL, or an Open Graph image. Classification:
     1. Suffix match: anything ending in _IMAGE / _PHOTO / _PORTRAIT /
        _ICON / _LOGO / _BG / _BACKGROUND / _AVATAR is always an image.
     2. Prefix match: well-known image-only namespaces (LOGO_, ICON_,
        HERO_, BG_, BACKGROUND_, FAVICON_, OG_IMAGE_, GALLERY_,
        SCREEN_, CREATIVE_, ROOM_, PRODUCT_, CHEF_, DESIGNER_, TILE_,
        TESTIMONIAL_, BLOG_, WORK_, LIPS_, PLACE_, SERVICE_,
        TREATMENT_).
     3. Description fallback when (1)+(2) miss: the keys.json line
        explicitly says "תמונת..." / "פורטרט..." / "אייקון..." /
        "רקע..." / "favicon" / "screenshot" / etc.

   The patterns deliberately exclude *_NAME, *_TEXT, EMAIL, ADDRESS,
   PHONE_*, WEBSITE_URL — those are text keys even when their NAME
   contains a substring that could read as an image (e.g. OWNER_NAME
   contains "OWNER"). Description is checked only after the name
   tests fail. */
const IMAGE_NAME_RE = /(?:_IMAGE|_PHOTO|_PORTRAIT|_ICON|_LOGO|_BG|_BACKGROUND|_AVATAR)$|^(?:LOGO|ICON|FAVICON|OG_IMAGE)(?:_|$)|^(?:HERO|BG|BACKGROUND)_(?:IMAGE|PHOTO|PORTRAIT|GLOW|GALLERY|BG)|^(?:GALLERY|SCREEN|CREATIVE|ROOM|PRODUCT|CHEF|DESIGNER|TILE|TESTIMONIAL|BLOG|WORK|LIPS|PLACE)(?:_|$)/;
const IMAGE_DESC_RE = /תמונ|פורטרט|אייקון|רקע|favicon|gallery|screenshot|מסך|^URL\sלל?(?:ו|תמונ)|background/i;

/* Hebrew description openers that mean "this is text content" — used
   to veto an image classification when the keys.json line explicitly
   says the field is a title / subtitle / paragraph / FAQ / etc.
   Without this veto, keys like HERO_TITLE_TOP get mis-classified as
   images via the ^HERO prefix and end up filled with Gemini-generated
   image URLs that are then rendered as visible text in <h1>. */
const TEXT_DESC_RE = /^(?:שורת|כותרת|תת-?\s*כותרת|תיאור|טקסט|פסקה|כפתור|cta|כתובת|אימייל|מייל|טלפון|שם|FAQ|שאלה|תשובה|מספר|זמן|סלוגן|tagline|headline|subheadline|נושא|תוכן)/i;

function isImageKey(keyName, description = "") {
  /* Description-first veto: explicit text indicators always win,
     even when the name happens to start with an image-ish prefix. */
  if (description && TEXT_DESC_RE.test(description.trim())) return false;
  if (IMAGE_NAME_RE.test(keyName)) return true;
  return !!description && IMAGE_DESC_RE.test(description);
}

/* An "icon key" is a tiny raster the LP needs for favicons, PWA
   icons (192/512/apple-touch), or 3D illustrative spot-icons (e.g.
   yassu's ICON_3D_BALLOONS). Gemini does poorly at small sizes and
   ignores brand colors, so we route icon keys to the brand logo
   instead of generating them — and leave a placehold.co stub when
   the brief has no logo, so the manager can upload a proper SVG
   icon later via the existing image-upload UI. */
const ICON_NAME_RE = /^FAVICON|^ICON(?:_|$)|_ICON$|_ICON_/;

function isIconKey(keyName) {
  return ICON_NAME_RE.test(keyName);
}

/* A value the AI assigned is "usable as-is" only when it's a real image
   URL we trust — brief-uploaded images (always served through /api/img),
   any logo passed in brief.logo, or any external URL the AI surfaced
   from brief.images directly. Empty values, placehold.co stubs, and
   anything that smells like a guess all need to be (re)generated. */
function isUsableImageValue(value, brief) {
  if (!value || typeof value !== "string") return false;
  const v = value.trim();
  if (!v) return false;
  if (/placehold\.co/i.test(v)) return false;
  if (v.startsWith("/api/img?")) return true;          // any image hosted on B2
  const briefImages = Array.isArray(brief?.images) ? brief.images : [];
  if (briefImages.includes(v)) return true;            // exact brief.images hit
  const logoUrl = brief?.logo || brief?.logoUrl || "";
  if (logoUrl && v === logoUrl) return true;
  /* Allow other absolute URLs through — the AI may have legit social /
     CDN URLs from the brief. Anything starting with http and not
     placehold.co is trusted. */
  return /^https?:\/\//i.test(v);
}

