/* Walk the HTML and replace every occurrence of an original Hebrew
   string with its rewritten version. Replacements are anchored to
   match either a text node, an attribute value, or a whitespace-
   normalized variant — so trivially different whitespace doesn't
   prevent a match. Strings inside <script>/<style> are skipped via
   the same strip-and-restore trick as extraction. */
function applyHebrewRewrites(html, rewriteMap) {
  if (!rewriteMap || rewriteMap.size === 0) return html;

  /* Stash <script>/<style> blocks to placeholders so substitutions
     don't touch code. */
  const stash = [];
  const stashHtml = html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, (m) => { stash.push(m); return `___STASH_${stash.length - 1}___`; })
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, (m) => { stash.push(m); return `___STASH_${stash.length - 1}___`; });

  /* Sort longest-first so a long string is matched before any
     substring of it (avoids partial replacements). */
  const entries = [...rewriteMap.entries()].sort((a, b) => b[0].length - a[0].length);

  let out = stashHtml;
  for (const [orig, replacement] of entries) {
    /* Literal split/join — faster than regex and immune to special
       regex chars in the Hebrew strings. */
    if (out.includes(orig)) {
      out = out.split(orig).join(replacement);
      continue;
    }
    /* Whitespace-normalized fallback for cases where the HTML has
       extra spaces or newlines around the text. */
    const looseRe = new RegExp(orig.split(/\s+/).map(t =>
      t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    ).join("\\s+"), "g");
    out = out.replace(looseRe, replacement);
  }

  /* Restore the stashed code blocks. */
  out = out.replace(/___STASH_(\d+)___/g, (_, i) => stash[Number(i)] || "");
  return out;
}

